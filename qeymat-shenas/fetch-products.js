// Fetches random real products from the Digikala search API and downloads their images.
const fs = require('fs');
const path = require('path');

const QUERIES = [
  'گوشی موبایل', 'هدفون', 'لپ تاپ', 'ساعت هوشمند', 'کتاب', 'کفش ورزشی', 'قهوه ساز',
  'اسباب بازی', 'عطر', 'کوله پشتی', 'ماگ', 'جارو برقی', 'شکلات', 'تلویزیون', 'دوچرخه',
  'ماوس', 'کرم مرطوب کننده', 'چای', 'پاوربانک', 'چادر مسافرتی', 'کتری برقی', 'عینک آفتابی',
];
const PER_QUERY = 6;
const UA = { 'User-Agent': 'Mozilla/5.0' };

const sleep = ms => new Promise(r => setTimeout(r, ms));

async function search(q) {
  const page = 1 + Math.floor(Math.random() * 3);
  const res = await fetch(`https://api.digikala.com/v1/search/?q=${encodeURIComponent(q)}&page=${page}`, { headers: UA });
  const j = await res.json();
  return (j.data && j.data.products) || [];
}

(async () => {
  const out = [];
  const seen = new Set();
  for (const q of QUERIES) {
    let products;
    try { products = await search(q); } catch (e) { console.error('fail', q, e.message); continue; }
    const good = products.filter(p =>
      p.status === 'marketable' && p.default_variant && p.default_variant.price &&
      p.default_variant.price.selling_price > 0 && p.images && p.images.main && p.images.main.url && p.images.main.url[0] &&
      !seen.has(p.id));
    good.sort(() => Math.random() - 0.5);
    for (const p of good.slice(0, PER_QUERY)) {
      seen.add(p.id);
      const imgUrl = p.images.main.url[0].replace(/h_300,w_300/, 'h_500,w_500');
      const file = `img/${p.id}.jpg`;
      try {
        const r = await fetch(imgUrl, { headers: UA });
        if (!r.ok) throw new Error(r.status);
        fs.writeFileSync(path.join(__dirname, file), Buffer.from(await r.arrayBuffer()));
      } catch (e) { console.error('img fail', p.id, e.message); continue; }
      out.push({
        id: p.id,
        title: p.title_fa,
        brand: p.data_layer && p.data_layer.brand,
        category: (p.data_layer && (p.data_layer.item_category3 || p.data_layer.item_category2)) || q,
        group: q,
        price: Math.round(p.default_variant.price.selling_price / 10), // rial -> toman
        image: file,
        url: 'https://www.digikala.com' + p.url.uri,
      });
    }
    console.log(q, '->', out.length);
    await sleep(400);
  }
  fs.writeFileSync(path.join(__dirname, 'products.js'),
    '// Auto-generated by fetch-products.js from the Digikala API\nwindow.PRODUCTS = ' + JSON.stringify(out, null, 1) + ';\n');
  console.log('total', out.length);
})();
